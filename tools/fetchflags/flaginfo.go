// The corner colour is the mean of a cornerWindow x cornerWindow square
// centred cornerInset pixels inside each top corner of the part of the flag
// shown in the frame. Sampling inside skips borders and anti-aliasing on the
// outermost pixels.
const (
	cornerInset  = 2
	cornerWindow = 3
)

// Info is the pixel size of a flag image and the colour of its top corners
// as shown in the image frame (0xRRGGBB).
type Info struct {
	W, H   int
	Corner uint32
}

// Infos decodes each code's flag and reads its size and corner colour. It
// fails listing every code whose file is missing, cannot be decoded or is too
// small to sample.
func Infos(dir string, codes []string) (map[string]Info, error) {
	infos := make(map[string]Info, len(codes))
	failed := map[string]string{}
	for _, code := range codes {
		info, err := readInfo(FlagPath(dir, code))
		if err != nil {
			failed[code] = err.Error()
			continue
		}
		infos[code] = info
	}
	if len(failed) > 0 {
		var lines []string
		for _, code := range sortedKeys(failed) {
			lines = append(lines, code+": "+failed[code])
		}
		return nil, errors.New("failed to read flags:\n  " + strings.Join(lines, "\n  "))
	}
	return infos, nil
}

func readInfo(path string) (Info, error) {
	f, err := os.Open(path)
	if err != nil {
		return Info{}, err
	}
	defer f.Close()
	img, err := png.Decode(f)
	if err != nil {
		return Info{}, err
	}
	left, right, err := cornerColors(img)
	if err != nil {
		return Info{}, err
	}
	b := img.Bounds()
	return Info{W: b.Dx(), H: b.Dy(), Corner: packRGB(meanRGB(left, right))}, nil
}

// cornerColors returns the mean colour near the top-left and top-right
// corners of the part of img shown when it fills the frame centred.
func cornerColors(img image.Image) (left, right [3]uint8, err error) {
	b := img.Bounds()
	w, h := b.Dx(), b.Dy()
	dx, dy := country.FrameCrop(w, h)
	half := cornerWindow / 2
	shownW, shownH := w-2*dx, h-2*dy
	if shownW < 2*(cornerInset+half)+2 || shownH < cornerInset+half+1 {
		return left, right, fmt.Errorf("%dx%d image is too small to sample its corners", w, h)
	}
	y := b.Min.Y + dy + cornerInset
	left = windowMean(img, b.Min.X+dx+cornerInset, y)
	right = windowMean(img, b.Min.X+w-1-dx-cornerInset, y)
	return left, right, nil
}

// windowMean returns the mean colour of the cornerWindow x cornerWindow
// square centred at (cx, cy), with transparent pixels laid over white.
func windowMean(img image.Image, cx, cy int) [3]uint8 {
	half := cornerWindow / 2
	var sum [3]int
	n := 0
	for y := cy - half; y <= cy+half; y++ {
		for x := cx - half; x <= cx+half; x++ {
			c := color.NRGBAModel.Convert(img.At(x, y)).(color.NRGBA)
			for i, v := range [3]uint8{c.R, c.G, c.B} {
				sum[i] += overWhite(v, c.A)
			}
			n++
		}
	}
	var mean [3]uint8
	for i := range sum {
		mean[i] = uint8((sum[i] + n/2) / n)
	}
	return mean
}

// overWhite returns the component c with alpha a laid over white, rounded.
func overWhite(c, a uint8) int {
	return (int(c)*int(a) + 255*(255-int(a)) + 127) / 255
}

// meanRGB returns the colour itself when both are equal and otherwise the
// rounded mean of each sRGB component.
func meanRGB(l, r [3]uint8) [3]uint8 {
	if l == r {
		return l
	}
	var m [3]uint8
	for i := range m {
		m[i] = uint8((int(l[i]) + int(r[i]) + 1) / 2)
	}
	return m
}

func packRGB(c [3]uint8) uint32 {
	return uint32(c[0])<<16 | uint32(c[1])<<8 | uint32(c[2])
}

// WriteInfos writes the Go source of internal/country/flags_gen.go, sorted by
// code.
func WriteInfos(w io.Writer, infos map[string]Info) error {
	codes := make([]string, 0, len(infos))
	for code := range infos {
		codes = append(codes, code)
	}
	slices.Sort(codes)

	var b bytes.Buffer
	b.WriteString("// Code generated by tools/fetchflags; DO NOT EDIT.\n\n")
	b.WriteString("package country\n\n")
	b.WriteString("// flagInfos is the pixel size of public/flags/{code}.png and the colour of\n")
	b.WriteString("// its top corners when shown in the image frame, keyed by ISO code.\n")
	b.WriteString("var flagInfos = map[string]flagInfo{\n")
	for _, code := range codes {
		in := infos[code]
		fmt.Fprintf(&b, "\t%q: {W: %d, H: %d, Corner: 0x%06X},\n", code, in.W, in.H, in.Corner)
	}
	b.WriteString("}\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		return err
	}
	_, err = w.Write(src)
	return err
}
