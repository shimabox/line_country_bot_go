func writePNG(t *testing.T, path string, w, h int) {
	t.Helper()
	var buf bytes.Buffer
	if err := png.Encode(&buf, image.NewRGBA(image.Rect(0, 0, w, h))); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, buf.Bytes(), 0o644); err != nil {
		t.Fatal(err)
	}
}

func TestSizes(t *testing.T) {
	dir := t.TempDir()
	writePNG(t, FlagPath(dir, "JP"), 30, 20)
	writePNG(t, FlagPath(dir, "GB"), 32, 16)
	writePNG(t, FlagPath(dir, "NP"), 16, 20)
	got, err := Sizes(dir, []string{"JP", "GB", "NP"})
	if err != nil {
		t.Fatalf("Sizes: %v", err)
	}
	want := map[string]Size{"JP": {W: 30, H: 20}, "GB": {W: 32, H: 16}, "NP": {W: 16, H: 20}}
	if !reflect.DeepEqual(got, want) {
		t.Errorf("Sizes = %v, want %v", got, want)
	}
}

func TestSizesReportsUnreadableFiles(t *testing.T) {
	dir := t.TempDir()
	writePNG(t, FlagPath(dir, "JP"), 30, 20)
	if err := os.WriteFile(FlagPath(dir, "TW"), fakePNG, 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(FlagPath(dir, "FR"), []byte("<html>not a png</html>"), 0o644); err != nil {
		t.Fatal(err)
	}
	_, err := Sizes(dir, []string{"JP", "TW", "XK", "FR"})
	if err == nil {
		t.Fatal("err = nil, want failure")
	}
	msg := err.Error()
	for _, code := range []string{"FR", "TW", "XK"} {
		if !strings.Contains(msg, code) {
			t.Errorf("error does not list %s: %v", code, err)
		}
	}
	if strings.Contains(msg, "JP") {
		t.Errorf("error lists a readable file: %v", err)
	}
	if i, j, k := strings.Index(msg, "FR"), strings.Index(msg, "TW"), strings.Index(msg, "XK"); !(i < j && j < k) {
		t.Errorf("codes not in order: %v", err)
	}
}

func TestWriteSizes(t *testing.T) {
	var buf bytes.Buffer
	err := WriteSizes(&buf, map[string]Size{
		"US": {W: 320, H: 168},
		"AD": {W: 320, H: 224},
		"JP": {W: 320, H: 213},
	})
	if err != nil {
		t.Fatalf("WriteSizes: %v", err)
	}
	want := `// Code generated by tools/fetchflags; DO NOT EDIT.

package country

// flagSizes is the pixel size of public/flags/{code}.png, keyed by ISO code.
var flagSizes = map[string]flagSize{
	"AD": {W: 320, H: 224},
	"JP": {W: 320, H: 213},
	"US": {W: 320, H: 168},
}
`
	if got := buf.String(); got != want {
		t.Errorf("output =\n%s\nwant\n%s", got, want)
	}
	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		t.Fatalf("output does not parse: %v", err)
	}
	if !bytes.Equal(formatted, buf.Bytes()) {
		t.Error("output is not gofmt-ed")
	}
}

