package main

import (
	"bytes"
	"errors"
	"fmt"
	"go/format"
	"image/png"
	"io"
	"os"
	"slices"
	"strings"
)

// Size is the pixel size of a flag image.
type Size struct {
	W, H int
}

// Sizes reads the width and height of each code's flag from the PNG header.
// It fails listing every code whose file is missing or unreadable.
func Sizes(dir string, codes []string) (map[string]Size, error) {
	sizes := make(map[string]Size, len(codes))
	failed := map[string]string{}
	for _, code := range codes {
		s, err := readSize(FlagPath(dir, code))
		if err != nil {
			failed[code] = err.Error()
			continue
		}
		sizes[code] = s
	}
	if len(failed) > 0 {
		var lines []string
		for _, code := range sortedKeys(failed) {
			lines = append(lines, code+": "+failed[code])
		}
		return nil, errors.New("failed to read flag sizes:\n  " + strings.Join(lines, "\n  "))
	}
	return sizes, nil
}

func readSize(path string) (Size, error) {
	f, err := os.Open(path)
	if err != nil {
		return Size{}, err
	}
	defer f.Close()
	cfg, err := png.DecodeConfig(f)
	if err != nil {
		return Size{}, err
	}
	return Size{W: cfg.Width, H: cfg.Height}, nil
}

// WriteSizes writes the Go source of internal/country/flagsizes_gen.go,
// sorted by code.
func WriteSizes(w io.Writer, sizes map[string]Size) error {
	codes := make([]string, 0, len(sizes))
	for code := range sizes {
		codes = append(codes, code)
	}
	slices.Sort(codes)

	var b bytes.Buffer
	b.WriteString("// Code generated by tools/fetchflags; DO NOT EDIT.\n\n")
	b.WriteString("package country\n\n")
	b.WriteString("// flagSizes is the pixel size of public/flags/{code}.png, keyed by ISO code.\n")
	b.WriteString("var flagSizes = map[string]flagSize{\n")
	for _, code := range codes {
		fmt.Fprintf(&b, "\t%q: {W: %d, H: %d},\n", code, sizes[code].W, sizes[code].H)
	}
	b.WriteString("}\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		return err
	}
	_, err = w.Write(src)
	return err
}
