// Command gencountrygo writes the country data in data/countries.json as Go
// source (internal/country/countries_gen.go), so the Worker starts without
// parsing JSON or building the lookup index. It is run by go generate:
//
//	go generate ./internal/country
//
// which runs
//
//	go run ../../tools/gencountrygo -in data/countries.json -out countries_gen.go
//
// The input is checked with country.Load and nothing is written when it
// fails.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"strconv"
	"strings"

	"github.com/shimabox/line_country_bot_go/internal/country"
)

func main() {
	in := flag.String("in", "", "countries.json to read")
	out := flag.String("out", "", "Go file to write")
	flag.Parse()
	if *in == "" || *out == "" {
		fmt.Fprintln(os.Stderr, "usage: gencountrygo -in <countries.json> -out <countries_gen.go>")
		os.Exit(2)
	}
	if err := run(*in, *out); err != nil {
		fmt.Fprintln(os.Stderr, "gencountrygo:", err)
		os.Exit(1)
	}
}

func run(in, out string) error {
	data, err := os.ReadFile(in)
	if err != nil {
		return err
	}
	src, err := Generate(data)
	if err != nil {
		return fmt.Errorf("%s: %w", in, err)
	}
	tmp := out + ".tmp"
	if err := os.WriteFile(tmp, src, 0o644); err != nil {
		return err
	}
	if err := os.Rename(tmp, out); err != nil {
		os.Remove(tmp)
		return err
	}
	return nil
}

// Generate returns the gofmt-formatted source of countries_gen.go for a
// countries document. It fails with country.Load's error when the document is
// invalid.
//
// The tables are arrays of strings, numbers and string slices, which the
// compiler lays out as static data, so no code runs to build them at start.
// The index refers to countries by position for the same reason.
func Generate(data []byte) ([]byte, error) {
	s, err := country.Load(data)
	if err != nil {
		return nil, err
	}
	index, err := country.BuildIndex(s.All())
	if err != nil {
		return nil, err
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by tools/gencountrygo; DO NOT EDIT.\n\n")
	b.WriteString("package country\n\n")
	b.WriteString("const (\n")
	fmt.Fprintf(&b, "\tgeneratedAt = %s\n", strconv.Quote(s.GeneratedAt()))
	fmt.Fprintf(&b, "\tsource = %s\n", strconv.Quote(s.Source()))
	b.WriteString(")\n\n")

	b.WriteString("// countryTable is the data set in data/countries.json order.\n")
	b.WriteString("var countryTable = [...]Country{\n")
	for _, c := range s.All() {
		b.WriteString("\t{" + countryFields(c) + "},\n")
	}
	b.WriteString("}\n\n")

	b.WriteString("// countryIndex maps a normalized name or alias to an index into countryTable.\n")
	b.WriteString("// It is sorted by Key and has no duplicates.\n")
	b.WriteString("var countryIndex = [...]IndexEntry{\n")
	for _, e := range index {
		fmt.Fprintf(&b, "\t{Key: %s, Index: %d},\n", strconv.Quote(e.Key), e.Index)
	}
	b.WriteString("}\n")

	return format.Source(b.Bytes())
}

// countryFields returns the fields of a Country composite literal. Empty
// strings and nil slices are left out so they keep their zero value, as when
// decoded from JSON.
func countryFields(c *country.Country) string {
	var fields []string
	str := func(name, v string, always bool) {
		if always || v != "" {
			fields = append(fields, name+": "+strconv.Quote(v))
		}
	}
	strs := func(name string, vs []string) {
		if vs == nil {
			return
		}
		quoted := make([]string, len(vs))
		for i, v := range vs {
			quoted[i] = strconv.Quote(v)
		}
		fields = append(fields, name+": []string{"+strings.Join(quoted, ", ")+"}")
	}
	num := func(name string, v float64) {
		fields = append(fields, name+": "+strconv.FormatFloat(v, 'g', -1, 64))
	}

	str("Code", c.Code, true)
	str("NameJA", c.NameJA, true)
	strs("AliasesJA", c.AliasesJA)
	strs("AliasesEN", c.AliasesEN)
	str("CapitalJA", c.CapitalJA, false)
	str("CapitalEN", c.CapitalEN, false)
	num("Lat", c.Lat)
	num("Lon", c.Lon)
	str("WikipediaJAURL", c.WikipediaJAURL, false)
	return strings.Join(fields, ", ")
}
