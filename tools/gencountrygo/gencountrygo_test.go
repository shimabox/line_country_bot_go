func readFixture(t *testing.T) []byte {
	t.Helper()
	data, err := os.ReadFile("../../internal/country/testdata/fixture.json")
	if err != nil {
		t.Fatal(err)
	}
	return data
}

func TestGenerateFixture(t *testing.T) {
	src, err := Generate(readFixture(t))
	if err != nil {
		t.Fatalf("Generate: %v", err)
	}
	if !bytes.HasPrefix(src, []byte("// Code generated by tools/gencountrygo; DO NOT EDIT.\n")) {
		t.Errorf("missing generated-code header:\n%s", src[:min(len(src), 200)])
	}
	formatted, err := format.Source(src)
	if err != nil {
		t.Fatalf("format.Source: %v", err)
	}
	if !bytes.Equal(formatted, src) {
		t.Error("output is not gofmt-formatted")
	}

	f, err := parser.ParseFile(token.NewFileSet(), "countries_gen.go", src, 0)
	if err != nil {
		t.Fatalf("parse: %v", err)
	}
	if f.Name.Name != "country" {
		t.Errorf("package = %s, want country", f.Name.Name)
	}
	decls := map[string]token.Token{}
	elems := map[string]int{}
	for _, d := range f.Decls {
		g, ok := d.(*ast.GenDecl)
		if !ok {
			t.Errorf("unexpected declaration %T", d)
			continue
		}
		for _, spec := range g.Specs {
			vs := spec.(*ast.ValueSpec)
			for i, n := range vs.Names {
				decls[n.Name] = g.Tok
				if lit, ok := vs.Values[i].(*ast.CompositeLit); ok {
					elems[n.Name] = len(lit.Elts)
				}
			}
		}
	}
	want := map[string]token.Token{
		"generatedAt":  token.CONST,
		"source":       token.CONST,
		"countryTable": token.VAR,
		"countryIndex": token.VAR,
	}
	for name, tok := range want {
		if decls[name] != tok {
			t.Errorf("%s: declared as %v, want %v", name, decls[name], tok)
		}
	}
	if len(decls) != len(want) {
		t.Errorf("declarations = %v, want only %v", decls, want)
	}

	s, err := country.Load(readFixture(t))
	if err != nil {
		t.Fatal(err)
	}
	index, err := country.BuildIndex(s.All())
	if err != nil {
		t.Fatal(err)
	}
	if elems["countryTable"] != s.Len() {
		t.Errorf("countryTable has %d elements, want %d", elems["countryTable"], s.Len())
	}
	if elems["countryIndex"] != len(index) {
		t.Errorf("countryIndex has %d elements, want %d", elems["countryIndex"], len(index))
	}
	for _, want := range []string{
		`generatedAt = "2026-01-01"`,
		`source      = "test fixture"`,
		`{Code: "JP", NameJA: "日本", AliasesJA: []string{"日本国", "にほん"}, AliasesEN: []string{"Japan"}, CapitalJA: "東京", CapitalEN: "Tokyo", Lat: 35.689, Lon: 139.692, WikipediaJAURL: "https://ja.wikipedia.org/wiki/%E6%97%A5%E6%9C%AC"},`,
		`{Key: "japan", Index: 3},`,
		"Lon: -77.036667",
	} {
		if !bytes.Contains(src, []byte(want)) {
			t.Errorf("output does not contain %s", want)
		}
	}
}

func TestGenerateDeterministic(t *testing.T) {
	data := readFixture(t)
	a, err := Generate(data)
	if err != nil {
		t.Fatal(err)
	}
	for i := 0; i < 5; i++ {
		b, err := Generate(data)
		if err != nil {
			t.Fatal(err)
		}
		if !bytes.Equal(a, b) {
			t.Fatal("same input gave different outputs")
		}
	}
}

func TestGenerateFailsLikeLoad(t *testing.T) {
	for name, body := range map[string]string{
		"invalid json":   `{`,
		"no countries":   `{"countries":[]}`,
		"duplicate code": `{"countries":[{"code":"JP","name_ja":"日本"},{"code":"JP","name_ja":"日本国"}]}`,
	} {
		_, loadErr := country.Load([]byte(body))
		if loadErr == nil {
			t.Fatalf("%s: Load accepted the input", name)
		}
		src, err := Generate([]byte(body))
		if err == nil {
			t.Errorf("%s: err = nil, want %v", name, loadErr)
			continue
		}
		if src != nil {
			t.Errorf("%s: output on error", name)
		}
		if !strings.Contains(err.Error(), loadErr.Error()) {
			t.Errorf("%s: err = %v, want Load's error %v", name, err, loadErr)
		}
	}
}

func TestRunWritesFile(t *testing.T) {
	dir := t.TempDir()
	in := dir + "/in.json"
	out := dir + "/out.go"
	if err := os.WriteFile(in, readFixture(t), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := run(in, out); err != nil {
		t.Fatalf("run: %v", err)
	}
	got, err := os.ReadFile(out)
	if err != nil {
		t.Fatal(err)
	}
	want, _ := Generate(readFixture(t))
	if !bytes.Equal(got, want) {
		t.Error("written file differs from Generate output")
	}

	if err := os.WriteFile(in, []byte("{"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := run(in, out); err == nil {
		t.Error("run with invalid JSON: err = nil")
	}
	if got2, _ := os.ReadFile(out); !bytes.Equal(got2, want) {
		t.Error("a failed run changed the output file")
	}
}
